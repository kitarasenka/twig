import assert from 'node:assert/strict';
import { _electron as electron } from 'playwright';
import { mkdtemp, mkdir, rm, writeFile, readFile, access } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { CommandLog } from '../main/command-log.js';
import { runGit } from '../main/git/exec.js';

const root = await mkdtemp(path.join(os.tmpdir(), 'twig-ssh-undo-ui-'));
let app;
try {
  const home = path.join(root, 'home'); const cwd = path.join(root, 'repo');
  await mkdir(home); await mkdir(cwd);
  const log = new CommandLog(root); await log.load();
  const git = async argv => { const result = await runGit({ cwd, log, argv }); assert.equal(result.code, 0, result.stderr); return result.stdout.trim(); };
  await git(['init', '--initial-branch=main']);
  for (const [key, value] of [['user.name', 'Twig Fixture'], ['user.email', 'twig@example.invalid'], ['commit.gpgsign', 'false'], ['core.hooksPath', '']]) await git(['config', key, value]);
  await writeFile(path.join(cwd, 'file.txt'), 'initial\n'); await git(['add', '--', 'file.txt']); await git(['commit', '-m', 'Initial']);
  const initial = await git(['rev-parse', 'HEAD']);
  const bootstrap = path.join(root, 'bootstrap.mjs');
  await writeFile(bootstrap, `import { app } from 'electron';\napp.setPath('home', ${JSON.stringify(home)});\napp.setPath('userData', ${JSON.stringify(path.join(root, 'profile'))});\nimport(${JSON.stringify(pathToFileURL(path.resolve('main/index.js')).href)});\n`);
  const env = { ...process.env, GIT_CONFIG_GLOBAL: path.join(root, 'global'), GIT_CONFIG_NOSYSTEM: '1' };
  delete env.ELECTRON_RUN_AS_NODE; delete env.TWIG_DEV;
  app = await electron.launch({ args: [bootstrap], env });
  let page = await app.firstWindow(); page.setDefaultTimeout(30000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.waitForFunction(() => Boolean(window.twig));
  assert.equal((await page.evaluate(() => window.twig.getSshConfig())).path, path.join(home, '.ssh', 'config'), 'never test SSH writes in the real user home');
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'SSH keys and config', exact: true }).click();
  const ssh = page.getByRole('dialog', { name: 'SSH', exact: true });
  await ssh.getByRole('textbox', { name: 'Key filename', exact: true }).fill('id_twig_fixture');
  await ssh.getByLabel('Passphrase', { exact: true }).fill('fixture-secret-for-ui');
  await ssh.getByLabel('Repeat passphrase', { exact: true }).fill('fixture-secret-for-ui');
  await ssh.getByRole('button', { name: 'Generate key', exact: true }).click();
  await ssh.getByText('id_twig_fixture.pub', { exact: true }).waitFor();
  assert.equal(await ssh.getByLabel('Passphrase', { exact: true }).inputValue(), '');
  await ssh.getByRole('button', { name: 'Copy public key', exact: true }).click();
  assert.match(await app.evaluate(({ clipboard }) => clipboard.readText()), /^ssh-ed25519 /);
  const configText = 'Host twig-loopback\n  HostName 127.0.0.1\n  Port 1\n  User git\n';
  await ssh.getByRole('textbox', { name: 'Configuration text', exact: true }).fill(configText);
  await ssh.getByRole('button', { name: 'Validate and save config', exact: true }).click();
  await ssh.getByText('SSH config created.', { exact: true }).waitFor();
  await ssh.getByRole('button', { name: 'Lines', exact: true }).click();
  await ssh.getByRole('textbox', { name: 'Config line 4', exact: true }).fill('  User twig');
  await ssh.getByRole('button', { name: 'Validate and save config', exact: true }).click();
  await ssh.getByRole('status').filter({ hasText: 'Saved. Backup:' }).waitFor();
  assert.match(await readFile(path.join(home, '.ssh', 'config'), 'utf8'), /User twig/);
  await ssh.getByRole('textbox', { name: 'SSH host', exact: true }).fill('twig-loopback');
  await ssh.getByRole('button', { name: 'Test SSH connection', exact: true }).click();
  await ssh.getByLabel('SSH connection output', { exact: true }).waitFor();
  await mkdir('artifacts', { recursive: true }); await page.setViewportSize({ width: 1000, height: 640 });
  for (const theme of ['dark', 'light']) {
    await page.evaluate(theme => { document.documentElement.dataset.theme = theme; }, theme);
    await ssh.getByRole('heading', { name: 'SSH keys', exact: true }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: `artifacts/m5-ssh-${theme}.png`, animations: 'disabled' });
    assert.equal(await ssh.evaluate(element => element.scrollWidth <= element.clientWidth), true);
  }
  const journal = await page.evaluate(() => window.twig.getConsoleEntries());
  assert.equal(JSON.stringify(journal).includes('fixture-secret-for-ui'), false);
  assert.ok(journal.some(entry => entry.executable === 'ssh' && entry.argv.includes('-T')));
  await page.keyboard.press('Escape');
  await app.evaluate(({ dialog }, directory) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [directory] }); }, cwd);
  await page.getByRole('button', { name: 'New repository tab', exact: true }).click();
  await page.getByRole('button', { name: 'Open repository', exact: true }).click();
  await page.getByRole('listbox', { name: 'Commit history', exact: true }).waitFor();
  const id = (await page.evaluate(() => window.twig.getWorkspace())).activeId;
  await writeFile(path.join(cwd, 'file.txt'), 'next\n');
  await page.evaluate(async id => { await window.twig.stageFile(id, 'file.txt'); await window.twig.createCommit(id, 'Recorded commit'); }, id);
  const committed = await git(['rev-parse', 'HEAD']);
  const undo = page.getByRole('button', { name: 'Undo', exact: true });
  await undo.waitFor();
  await page.getByRole('listbox', { name: 'Commit history', exact: true }).focus();
  await page.keyboard.press(process.platform === 'darwin' ? 'Meta+z' : 'Control+z');
  await page.getByText('Undo completed.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Redo', exact: true }).waitFor();
  assert.equal(await git(['rev-parse', 'HEAD']), initial);
  const redo = page.getByRole('button', { name: 'Redo', exact: true });
  await redo.click();
  await page.getByText('Redo completed.', { exact: true }).waitFor();
  assert.equal(await git(['rev-parse', 'HEAD']), committed);
  await page.evaluate(async ({ id, committed }) => { await window.twig.createBranch(id, 'ui-branch', committed, false); }, { id, committed });
  await undo.click();
  await page.getByText('Undo completed.', { exact: true }).waitFor();
  await redo.waitFor();
  assert.equal((await git(['for-each-ref', '--format=%(refname)', 'refs/heads/ui-branch'])), '');
  await app.close(); app = await electron.launch({ args: [bootstrap], env });
  page = await app.firstWindow(); page.setDefaultTimeout(30000);
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await page.getByText('Redo completed.', { exact: true }).waitFor();
  assert.equal(await git(['rev-parse', 'ui-branch']), committed);
  await writeFile(path.join(cwd, 'external.txt'), 'keep this\n');
  const state = await page.evaluate(id => window.twig.getUndoState(id), id);
  assert.equal(state.undo, false);
  const refused = await page.evaluate(async id => {
    const calls = [() => window.twig.moveUndo(id, 'undo'), () => window.twig.moveUndo(id, 'bad'),
      () => window.twig.generateSshKey('../escape', '', 'test'), () => window.twig.testSshConnection('--bad'),
      () => window.twig.saveSshConfig('Host x\n', 'stale')];
    return Promise.all(calls.map(async call => { try { await call(); return false; } catch { return true; } }));
  }, id);
  assert.deepEqual(refused, [true, true, true, true, true]); await access(path.join(cwd, 'external.txt'));
  assert.deepEqual(errors, []);
  console.log('SSH/Undo Electron passed: isolated encrypted keys, clipboard, config text/lines/backups, loopback SSH output, themes, commit/branch Undo/Redo, restart, external edits and IPC refusal.');
} finally { await app?.close(); await rm(root, { recursive: true, force: true }); }
